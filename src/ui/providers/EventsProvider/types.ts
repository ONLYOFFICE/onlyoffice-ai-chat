import type { ThreadMessageLike } from "@assistant-ui/react";
import type {
  Profile,
  ProviderType,
  TAttachmentRef,
} from "../../../types";

// ---------------------------------------------------------------------------
// Message events
// ---------------------------------------------------------------------------

/**
 * Fired when the user sends a new message in a thread.
 * Includes the composed message and any file/image attachments.
 */
export interface MessageSentEvent {
  threadId: string;
  message: ThreadMessageLike;
  attachments: {
    files?: TAttachmentRef[];
    images?: TAttachmentRef[];
  };
}

/**
 * Fired when the provider begins streaming a response for a message.
 */
export interface StreamStartEvent {
  threadId: string;
  messageUID: string;
}

/**
 * Fired for each incremental chunk received during a streaming response.
 * The `message` field contains the accumulated content so far.
 */
export interface StreamDeltaEvent {
  threadId: string;
  messageUID: string;
  message: ThreadMessageLike;
}

/**
 * Fired when the provider finishes streaming a response successfully.
 * The `message` field contains the final, complete message.
 */
export interface StreamEndEvent {
  threadId: string;
  messageUID: string;
  message: ThreadMessageLike;
}

/**
 * Fired when the provider stream encounters an error and cannot continue.
 */
export interface StreamErrorEvent {
  threadId: string;
  messageUID: string;
  error: {
    reason: string;
    message?: string;
  };
}

/**
 * Fired when the user manually stops (cancels) an in-progress stream.
 */
export interface StreamStopEvent {
  threadId: string;
  messageUID: string;
}

// ---------------------------------------------------------------------------
// Tool call events
// ---------------------------------------------------------------------------

/**
 * Fired when a tool call requires user approval before execution.
 */
export interface ToolCallPendingEvent {
  threadId: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
  messageUID: string;
}

/**
 * Fired when the user approves a pending tool call.
 * If `allowAlways` is true, future calls to the same tool are auto-approved.
 */
export interface ToolCallApprovedEvent {
  threadId: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
  allowAlways: boolean;
}

/**
 * Fired when the user denies a pending tool call.
 */
export interface ToolCallDeniedEvent {
  threadId: string;
  toolName: string;
}

/**
 * Fired when a tool call completes and returns its result.
 */
export interface ToolCallResultEvent {
  threadId: string;
  toolName: string;
  result: unknown;
}

/**
 * Fired when a tool call is automatically approved (e.g. the user previously
 * selected "always allow" for this tool).
 */
export interface ToolCallAutoApprovedEvent {
  threadId: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// Aggregate "updated" events
// ---------------------------------------------------------------------------

/** Discriminator for {@link ThreadsUpdatedEvent}. */
export type ThreadsUpdateKind =
  | "created"
  | "switched"
  | "renamed"
  | "cleared"
  | "deleted";

/**
 * Single source of truth for thread lifecycle changes. The `kind`
 * discriminator narrows the rest of the payload — e.g. `"renamed"`
 * carries `title` and `isAutoGenerated`, `"switched"` carries
 * `previousThreadId`.
 */
export type ThreadsUpdatedEvent =
  | { kind: "created"; threadId: string; title?: string }
  | { kind: "switched"; threadId: string; previousThreadId: string }
  | {
      kind: "renamed";
      threadId: string;
      title: string;
      isAutoGenerated: boolean;
    }
  | { kind: "cleared"; threadId: string }
  | { kind: "deleted"; threadId: string };

/** Discriminator for {@link ProfilesUpdatedEvent}. */
export type ProfilesUpdateKind = "created" | "updated" | "deleted";

/**
 * Single source of truth for profile inventory changes. `"created"`
 * and `"updated"` carry the full {@link Profile}; `"deleted"` carries
 * only the id.
 */
export type ProfilesUpdatedEvent =
  | { kind: "created"; profile: Profile }
  | { kind: "updated"; profile: Profile }
  | { kind: "deleted"; profileId: string };

/**
 * Fired whenever the effective chat profile changes — either via a
 * session-scoped selection in the composer (`scope: "session"`) or via
 * a persisted Model Assignment change (`scope: "persisted"`).
 */
export interface CurrentChatProfileUpdatedEvent {
  profileId: string | null;
  scope: "session" | "persisted";
  providerType?: ProviderType;
  modelId?: string;
}

/** Task slot on the Model Assignment page. */
export type ModelAssignmentTask =
  | "default"
  | "chat"
  | "summarization"
  | "translation"
  | "textAnalysis"
  | "imageGeneration"
  | "ocr"
  | "vision";

/**
 * Fired whenever a profile is bound to or cleared from a task slot.
 */
export interface ModelAssignmentUpdatedEvent {
  task: ModelAssignmentTask;
  profileId: string | null;
}

/** Discriminator for {@link ServersUpdatedEvent}. */
export type ServersUpdateKind =
  | "config-saved"
  | "server-deleted"
  | "tool-toggled"
  | "tool-auto-approve-changed";

/**
 * Fired whenever MCP server config or per-tool state changes.
 */
export interface ServersUpdatedEvent {
  kind: ServersUpdateKind;
  serverName?: string;
  toolType?: string;
  toolName?: string;
  enabled?: boolean;
  allowAlways?: boolean;
}

/**
 * Fired whenever Web Search configuration changes (provider switch,
 * credentials update, or disabling it entirely).
 */
export interface WebSearchUpdatedEvent {
  enabled: boolean;
  provider: string | null;
  isCloudProvider?: boolean;
}

/**
 * Fired whenever the "extended thinking" / deep-mode toggle changes
 * (via the composer button, {@link toggleExtendedThinking}, or an
 * external re-sync).
 */
export interface ExtendedThinkingUpdatedEvent {
  enabled: boolean;
}

// ---------------------------------------------------------------------------
// Error events
// ---------------------------------------------------------------------------

/**
 * Fired when an error occurs anywhere in the chat system.
 * The `type` field categorizes the error source (provider, tool, network,
 * or storage), and `context` provides optional additional detail.
 */
export interface ChatErrorEvent {
  type: "provider" | "tool" | "network" | "storage";
  error: unknown;
  context?: string;
}

// ---------------------------------------------------------------------------
// ChatCallbacks — full callback interface
// ---------------------------------------------------------------------------

/**
 * Complete set of optional callbacks that consumers can register to observe
 * chat widget lifecycle events. Every callback receives a strongly-typed
 * event payload and returns `void`.
 *
 * @example
 * ```ts
 * const callbacks: ChatCallbacks = {
 *   onMessageSent(data) {
 *     console.log(`User sent message in thread ${data.threadId}`);
 *   },
 *   onStreamEnd(data) {
 *     analytics.track("response_complete", { threadId: data.threadId });
 *   },
 *   onError(data) {
 *     errorReporter.capture(data.error, { type: data.type });
 *   },
 * };
 * ```
 */
export interface ChatCallbacks {
  // Messages
  onMessageSent?: (data: MessageSentEvent) => void;
  onStreamStart?: (data: StreamStartEvent) => void;
  onStreamDelta?: (data: StreamDeltaEvent) => void;
  onStreamEnd?: (data: StreamEndEvent) => void;
  onStreamError?: (data: StreamErrorEvent) => void;
  onStreamStop?: (data: StreamStopEvent) => void;
  // Tool calls
  onToolCallPending?: (data: ToolCallPendingEvent) => void;
  onToolCallApproved?: (data: ToolCallApprovedEvent) => void;
  onToolCallDenied?: (data: ToolCallDeniedEvent) => void;
  onToolCallResult?: (data: ToolCallResultEvent) => void;
  onToolCallAutoApproved?: (data: ToolCallAutoApprovedEvent) => void;
  // Aggregate updates
  onThreadsUpdated?: (data: ThreadsUpdatedEvent) => void;
  onProfilesUpdated?: (data: ProfilesUpdatedEvent) => void;
  onCurrentChatProfileUpdated?: (data: CurrentChatProfileUpdatedEvent) => void;
  onModelAssignmentUpdated?: (data: ModelAssignmentUpdatedEvent) => void;
  onServersUpdated?: (data: ServersUpdatedEvent) => void;
  onWebSearchUpdated?: (data: WebSearchUpdatedEvent) => void;
  onExtendedThinkingUpdated?: (data: ExtendedThinkingUpdatedEvent) => void;
  // Errors
  onError?: (data: ChatErrorEvent) => void;
}
