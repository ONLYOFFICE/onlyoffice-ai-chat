import type { ThreadMessageLike } from "@assistant-ui/react";
import type { Profile, TAttachmentFile, TAttachmentImage } from "../types";

// ---------------------------------------------------------------------------
// Message events
// ---------------------------------------------------------------------------

/**
 * Fired when the user sends a new message in a thread.
 * Includes the composed message and any file/image attachments.
 */
export interface MessageSentEvent {
  threadId: string;
  message: ThreadMessageLike;
  attachments: {
    files?: TAttachmentFile[];
    images?: TAttachmentImage[];
  };
}

/**
 * Fired when the provider begins streaming a response for a message.
 */
export interface StreamStartEvent {
  threadId: string;
  messageUID: string;
}

/**
 * Fired for each incremental chunk received during a streaming response.
 * The `message` field contains the accumulated content so far.
 */
export interface StreamDeltaEvent {
  threadId: string;
  messageUID: string;
  message: ThreadMessageLike;
}

/**
 * Fired when the provider finishes streaming a response successfully.
 * The `message` field contains the final, complete message.
 */
export interface StreamEndEvent {
  threadId: string;
  messageUID: string;
  message: ThreadMessageLike;
}

/**
 * Fired when the provider stream encounters an error and cannot continue.
 */
export interface StreamErrorEvent {
  threadId: string;
  messageUID: string;
  error: {
    reason: string;
    message?: string;
  };
}

/**
 * Fired when the user manually stops (cancels) an in-progress stream.
 */
export interface StreamStopEvent {
  threadId: string;
  messageUID: string;
}

// ---------------------------------------------------------------------------
// Tool call events
// ---------------------------------------------------------------------------

/**
 * Fired when a tool call requires user approval before execution.
 */
export interface ToolCallPendingEvent {
  threadId: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
  messageUID: string;
}

/**
 * Fired when the user approves a pending tool call.
 * If `allowAlways` is true, future calls to the same tool are auto-approved.
 */
export interface ToolCallApprovedEvent {
  threadId: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
  allowAlways: boolean;
}

/**
 * Fired when the user denies a pending tool call.
 */
export interface ToolCallDeniedEvent {
  threadId: string;
  toolName: string;
}

/**
 * Fired when a tool call completes and returns its result.
 */
export interface ToolCallResultEvent {
  threadId: string;
  toolName: string;
  result: unknown;
}

/**
 * Fired when a tool call is automatically approved (e.g. the user previously
 * selected "always allow" for this tool).
 */
export interface ToolCallAutoApprovedEvent {
  threadId: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// Thread events
// ---------------------------------------------------------------------------

/**
 * Fired when a new chat thread is created.
 */
export interface ThreadCreatedEvent {
  threadId: string;
  title?: string;
}

/**
 * Fired when the active thread changes.
 */
export interface ThreadSwitchedEvent {
  threadId: string;
  previousThreadId: string;
}

/**
 * Fired when a thread is permanently deleted.
 */
export interface ThreadDeletedEvent {
  threadId: string;
}

/**
 * Fired when a thread is renamed, either manually by the user or
 * automatically by the system (indicated by `isAutoGenerated`).
 */
export interface ThreadRenamedEvent {
  threadId: string;
  title: string;
  isAutoGenerated: boolean;
}

/**
 * Fired when all messages in a thread are cleared.
 */
export interface ThreadClearedEvent {
  threadId: string;
}

// ---------------------------------------------------------------------------
// Profile events
// ---------------------------------------------------------------------------

/**
 * Fired when the user switches to a different AI profile (provider + model).
 */
export interface ProfileChangedEvent {
  profileId: string;
  providerType: string;
  modelId: string;
}

/**
 * Fired when a new AI profile is created.
 */
export interface ProfileCreatedEvent {
  profile: Profile;
}

/**
 * Fired when an AI profile is deleted.
 */
export interface ProfileDeletedEvent {
  profileId: string;
}

// ---------------------------------------------------------------------------
// Error events
// ---------------------------------------------------------------------------

/**
 * Fired when an error occurs anywhere in the chat system.
 * The `type` field categorizes the error source (provider, tool, network,
 * or storage), and `context` provides optional additional detail.
 */
export interface ChatErrorEvent {
  type: "provider" | "tool" | "network" | "storage";
  error: unknown;
  context?: string;
}

// ---------------------------------------------------------------------------
// ChatCallbacks — full callback interface
// ---------------------------------------------------------------------------

/**
 * Complete set of optional callbacks that consumers can register to observe
 * chat widget lifecycle events. Every callback receives a strongly-typed
 * event payload and returns `void`.
 *
 * @example
 * ```ts
 * const callbacks: ChatCallbacks = {
 *   onMessageSent(data) {
 *     console.log(`User sent message in thread ${data.threadId}`);
 *   },
 *   onStreamEnd(data) {
 *     analytics.track("response_complete", { threadId: data.threadId });
 *   },
 *   onError(data) {
 *     errorReporter.capture(data.error, { type: data.type });
 *   },
 * };
 * ```
 */
export interface ChatCallbacks {
  // Messages
  onMessageSent?: (data: MessageSentEvent) => void;
  onStreamStart?: (data: StreamStartEvent) => void;
  onStreamDelta?: (data: StreamDeltaEvent) => void;
  onStreamEnd?: (data: StreamEndEvent) => void;
  onStreamError?: (data: StreamErrorEvent) => void;
  onStreamStop?: (data: StreamStopEvent) => void;
  // Tool calls
  onToolCallPending?: (data: ToolCallPendingEvent) => void;
  onToolCallApproved?: (data: ToolCallApprovedEvent) => void;
  onToolCallDenied?: (data: ToolCallDeniedEvent) => void;
  onToolCallResult?: (data: ToolCallResultEvent) => void;
  onToolCallAutoApproved?: (data: ToolCallAutoApprovedEvent) => void;
  // Threads
  onThreadCreated?: (data: ThreadCreatedEvent) => void;
  onThreadSwitched?: (data: ThreadSwitchedEvent) => void;
  onThreadDeleted?: (data: ThreadDeletedEvent) => void;
  onThreadRenamed?: (data: ThreadRenamedEvent) => void;
  onThreadCleared?: (data: ThreadClearedEvent) => void;
  // Profiles
  onProfileChanged?: (data: ProfileChangedEvent) => void;
  onProfileCreated?: (data: ProfileCreatedEvent) => void;
  onProfileDeleted?: (data: ProfileDeletedEvent) => void;
  // Errors
  onError?: (data: ChatErrorEvent) => void;
}
