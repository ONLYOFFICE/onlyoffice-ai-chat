import { useCallback, useRef, useState } from "react";
import type { ChatCallbacks } from "@onlyoffice/ai-chat";

export interface LogEntry {
  id: number;
  time: string;
  event: string;
  data: Record<string, unknown>;
}

let nextId = 0;

function now(): string {
  return new Date().toLocaleTimeString("en-GB", {
    hour12: false,
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
}

export function useEventLog() {
  const [entries, setEntries] = useState<LogEntry[]>([]);
  const entriesRef = useRef(entries);
  entriesRef.current = entries;

  const push = useCallback((event: string, data: Record<string, unknown>) => {
    const entry: LogEntry = { id: nextId++, time: now(), event, data };
    setEntries((prev) => [entry, ...prev]);
  }, []);

  const clear = useCallback(() => {
    setEntries([]);
  }, []);

  const callbacks: ChatCallbacks = {
    onMessageSent: (e) => push("onMessageSent", { threadId: e.threadId }),
    onStreamStart: (e) =>
      push("onStreamStart", { threadId: e.threadId, messageUID: e.messageUID }),
    onStreamDelta: (e) =>
      push("onStreamDelta", { threadId: e.threadId, messageUID: e.messageUID }),
    onStreamEnd: (e) =>
      push("onStreamEnd", { threadId: e.threadId, messageUID: e.messageUID }),
    onStreamError: (e) =>
      push("onStreamError", {
        threadId: e.threadId,
        reason: e.error.reason,
      }),
    onStreamStop: (e) => push("onStreamStop", { threadId: e.threadId }),
    onToolCallPending: (e) =>
      push("onToolCallPending", { toolName: e.toolName }),
    onToolCallApproved: (e) =>
      push("onToolCallApproved", {
        toolName: e.toolName,
        allowAlways: e.allowAlways,
      }),
    onToolCallDenied: (e) => push("onToolCallDenied", { toolName: e.toolName }),
    onToolCallResult: (e) => push("onToolCallResult", { toolName: e.toolName }),
    onToolCallAutoApproved: (e) =>
      push("onToolCallAutoApproved", { toolName: e.toolName }),
    onThreadCreated: (e) => push("onThreadCreated", { threadId: e.threadId }),
    onThreadSwitched: (e) =>
      push("onThreadSwitched", {
        threadId: e.threadId,
        previousThreadId: e.previousThreadId,
      }),
    onThreadDeleted: (e) => push("onThreadDeleted", { threadId: e.threadId }),
    onThreadRenamed: (e) =>
      push("onThreadRenamed", {
        threadId: e.threadId,
        title: e.title,
        isAutoGenerated: e.isAutoGenerated,
      }),
    onThreadCleared: (e) => push("onThreadCleared", { threadId: e.threadId }),
    onProfileChanged: (e) =>
      push("onProfileChanged", {
        profileId: e.profileId,
        providerType: e.providerType,
      }),
    onProfileCreated: (e) =>
      push("onProfileCreated", { profileId: e.profile.id }),
    onProfileDeleted: (e) =>
      push("onProfileDeleted", { profileId: e.profileId }),
    onError: (e) => push("onError", { type: e.type, context: e.context }),
  };

  return { entries, callbacks, clear };
}
